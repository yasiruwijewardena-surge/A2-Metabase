import puppeteer from 'puppeteer-core';
const b=await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,protocolTimeout:180000,args:['--no-sandbox']});
const p=await b.newPage(); const errs=[]; p.on('pageerror',e=>errs.push(String(e)));
await p.setViewport({width:1512,height:1000});
await p.goto('http://127.0.0.1:4399/product/business-intelligence',{waitUntil:'networkidle2'});
await p.evaluate(()=>new Promise(r=>{document.querySelector('[data-carousel]')?.scrollIntoView({block:'center'});setTimeout(r,800);}));
const state = () => p.evaluate(()=>{
  const root=document.querySelector('[data-carousel]');
  const rs=[...root.querySelectorAll('.pp-feature-radio')];
  const i=rs.findIndex(r=>r.checked);
  const fill=root.querySelector('.pp-feature:has(.pp-feature-radio:checked) .pp-feature-fill');
  const shots=[...root.querySelectorAll('.pp-accordion-shot')].map(s=>getComputedStyle(s).display);
  return {open:i, fillH:fill?getComputedStyle(fill).height:null, shots, paused:root.dataset.paused};
});
console.log('t=0    ', JSON.stringify(await state()));
await p.evaluate(()=>new Promise(r=>setTimeout(r,3000)));
console.log('t=3s   ', JSON.stringify(await state()));
await p.evaluate(()=>new Promise(r=>setTimeout(r,4000)));
console.log('t=7s   ', JSON.stringify(await state()));
console.log('errors:', errs.length?errs[0].slice(0,90):'none');
await b.close();
